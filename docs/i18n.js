(function () {
  const KEY = "portfolio-lang";
  function initial() {
    const q = new URLSearchParams(location.search).get("lang");
    if (q === "en" || q === "id") return q;
    try {
      const s = localStorage.getItem(KEY);
      if (s === "en" || s === "id") return s;
    } catch (e) {}
    return (navigator.language || "en").toLowerCase().startsWith("id") ? "id" : "en";
  }
  function apply(lang) {
    const dict = STRINGS[lang];
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const v = dict[el.dataset.i18n];
      if (v !== undefined) el.textContent = v;
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const v = dict[el.dataset.i18nAria];
      if (v !== undefined) el.setAttribute("aria-label", v);
    });
    const t = document.querySelector("title");
    if (t && t.dataset.i18n === undefined) {
      const key = document.body.dataset.titleKey;
      if (key && dict[key]) t.textContent = dict[key] + " — Adil Rahmat Hidayah";
      else t.textContent = dict.site_title;
    }
    document.querySelectorAll(".lang-toggle button").forEach((b) => {
      b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
    });
    document.querySelectorAll("a[data-cv]").forEach((a) => {
      a.setAttribute("href", (a.dataset.base || "") + "assets/cv-" + lang + ".pdf");
    });
    try {
      localStorage.setItem(KEY, lang);
    } catch (e) {}
  }
  window.addEventListener("DOMContentLoaded", () => {
    document.querySelectorAll(".lang-toggle button").forEach((b) => {
      b.addEventListener("click", () => apply(b.dataset.lang));
    });
    apply(initial());
  });
})();
